const normalize = (v) =>
  String(v || "")
    .toLowerCase()
    .replace(/&apos;|'/g, "")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");

const pick = (...candidates) => {
  for (const candidate of candidates) {
    const raw = String(candidate || "").trim();
    if (raw.startsWith("http://") || raw.startsWith("https://") || raw.startsWith("/")) return raw;
  }
  return "";
};

